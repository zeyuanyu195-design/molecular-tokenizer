/* Replays verified static traces; no chemistry library or tokenizer runs in the browser. */
(() => {
  'use strict';
  const root = document.getElementById('connection-demo');
  if (!root) return;
  const colors = ['#247e91', '#a85479', '#92752b', '#5576ab', '#498464', '#986643', '#8062aa', '#5b8184'];
  const labels = ['Input graph', 'GraphBPE motifs', 'Boundary check', 'SAFE connections', 'Vocabulary IDs', 'Decode'];
  let data, exampleIndex = 0, step = 0, selectedPair = null, selectedFragment = 0, timer = null;
  const el = id => document.getElementById(id);
  const node = (tag, text, className) => {
    const n = document.createElement(tag);
    if (text !== undefined) n.textContent = text;
    if (className) n.className = className;
    return n;
  };
  const svgNode = (tag, attrs) => {
    const n = document.createElementNS('http://www.w3.org/2000/svg', tag);
    Object.entries(attrs).forEach(([k, v]) => n.setAttribute(k, v));
    return n;
  };
  const sample = () => data.examples[exampleIndex];
  const color = i => colors[i % colors.length];
  function pause() {
    clearInterval(timer); timer = null;
    el('cd-play').textContent = 'Auto play';
    el('cd-play').setAttribute('aria-pressed', 'false');
  }
  function setStep(value) {
    step = Math.max(0, Math.min(labels.length - 1, value));
    if (step === labels.length - 1) pause();
    render();
  }
  function descriptions(e) {
    const protectedBond = e.bonds.find(b => b.protected);
    return [
      'Start from the original SMILES. The atom numbers shown here are the zero-based source indices used throughout this walkthrough.',
      `The saved GraphBPE partition contains ${e.bpe_groups.length} motifs. Colors identify motif membership. This view shows the verified final partition; no intermediate merge history is invented.`,
      e.exact
        ? 'All 7 proposed cuts are accepted. The final SAFE atom partition equals the GraphBPE partition: 8 motifs remain 8 fragments. This record is included in the fixed-boundary comparison.'
        : `GraphBPE proposes 3 cuts. The current converter retains the E-configured double bond between atoms ${protectedBond.atoms.join(' and ')}. Two cuts remain, so 4 GraphBPE motifs become 3 SAFE fragments. This record is excluded from the fixed-boundary comparison, but it still decodes correctly.`,
      'Dots separate fragments. Cross-fragment ring-label pairs specify which atoms reconnect. Select a label below: its two occurrences, attachment atoms and matching bond light up together. Internal ring labels are shown separately.',
      e.exact
        ? 'Extract each fixed fragment from the complete parsed SAFE graph, derive its DemoDiff-compatible motif key and look up its ID. No second GraphBPE pass occurs. The eight IDs do not include the connection labels.'
        : 'Keeping the final SAFE boundaries produces three lookup units. The merged large fragment has no entry in the loaded vocabulary, so its result is “not in vocabulary”. The four original GraphBPE IDs cannot be relabelled as three SAFE-fragment IDs.',
      'Decode the complete SAFE string, including paired labels, their atom positions and bond/stereo syntax. The verified canonical isomeric SMILES matches the source. No separate attachment table is supplied to the decoder; motif IDs alone are insufficient.'
    ];
  }
  function highlightAtom(index) {
    root.querySelectorAll('[data-lex-atom]').forEach(n => n.classList.toggle('cd-hover', Number(n.dataset.lexAtom) === index));
    el('cd-atom-info').textContent = index === null
      ? 'Point to an atom to locate it in the SAFE text. Atom indices start at 0.'
      : `Atom ${index} · ${sample().atoms[index].element} · SAFE fragment F${sample().atoms[index].fragment + 1}`;
  }
  function renderGraph(e) {
    const graph = el('cd-graph');
    // SVG is generated by RDKit from the checked-in, verified molecules.
    graph.innerHTML = e.svg;
    const svg = graph.querySelector('svg');
    svg.removeAttribute('width'); svg.removeAttribute('height');
    svg.setAttribute('viewBox', '0 0 700 430');
    svg.setAttribute('role', 'img'); svg.setAttribute('aria-label', `${e.chembl_id}: ${labels[step]}. Numbered molecular graph.`);
    const underlay = svgNode('g', {'aria-hidden': 'true'});
    const background = svg.querySelector('rect');
    if (background) background.after(underlay); else svg.prepend(underlay);
    const pair = e.pairs.find(p => p.id === selectedPair);
    for (const atom of e.atoms) {
      if (step > 0) {
        const group = step === 1 ? atom.bpe : atom.fragment;
        underlay.append(svgNode('circle', {cx: atom.x, cy: atom.y, r: 15, fill: color(group), opacity: .19}));
      }
      if (step >= 3 && pair?.atoms.includes(atom.id)) {
        underlay.append(svgNode('circle', {cx: atom.x, cy: atom.y, r: 20, fill: '#f5b955', opacity: .65, stroke: '#8c5416', 'stroke-width': 1.5}));
      } else if (step === 4 && atom.fragment === selectedFragment) {
        underlay.append(svgNode('circle', {cx: atom.x, cy: atom.y, r: 19, fill: color(atom.fragment), opacity: .3}));
      }
    }
    for (const bond of e.bonds) {
      const [a, b] = bond.atoms.map(i => e.atoms[i]);
      if ((step === 3 || step === 4) && bond.used) {
        svg.querySelectorAll(`.bond-${bond.id}`).forEach(n => n.style.opacity = '0');
      }
      let stroke = null, dashed = false;
      if (step === 1 && bond.requested) {stroke = '#6d7578'; dashed = true;}
      if (step === 2 && bond.requested) {stroke = bond.protected ? '#c46020' : '#247e91'; dashed = !bond.protected;}
      if (step >= 3 && pair?.bond === bond.id) {stroke = '#cb8a22'; dashed = step < 5 && bond.used;}
      if (stroke) underlay.append(svgNode('line', {x1: a.x, y1: a.y, x2: b.x, y2: b.y,
        stroke, 'stroke-width': 11, 'stroke-opacity': .55, 'stroke-dasharray': dashed ? '5 5' : 'none'}));
    }
    // Transparent hit targets retain RDKit's chemical drawing and source numbering.
    for (const atom of e.atoms) {
      const hit = svgNode('circle', {cx: atom.x, cy: atom.y, r: 13, fill: 'transparent',
        tabindex: 0, role: 'button', 'aria-label': `Atom ${atom.id}, ${atom.element}, fragment F${atom.fragment + 1}`,
        class: 'cd-atom-target'});
      hit.append(svgNode('title', {}));
      hit.firstChild.textContent = `Atom ${atom.id}: ${atom.element}`;
      hit.addEventListener('mouseenter', () => highlightAtom(atom.id));
      hit.addEventListener('focus', () => highlightAtom(atom.id));
      hit.addEventListener('mouseleave', () => highlightAtom(null));
      hit.addEventListener('blur', () => highlightAtom(null));
      const select = () => {
        if (step < 3) return;
        selectedFragment = atom.fragment;
        selectedPair = e.pairs.find(p => p.cross_fragment && p.atoms.includes(atom.id))?.id ?? selectedPair;
        render();
      };
      hit.addEventListener('click', select);
      hit.addEventListener('keydown', event => {if (event.key === 'Enter' || event.key === ' ') {event.preventDefault(); select();}});
      svg.append(hit);
    }
    el('cd-graph-caption').textContent = step === 0 ? 'Original molecular graph · source atom indices'
      : step === 1 ? 'Colors: GraphBPE motifs · dashed highlights: proposed cuts'
      : step === 2 ? 'Colors: final SAFE fragments · blue dashes: accepted cuts · orange: retained bond'
      : step === 5 ? 'Reconstructed bonds · selected connection highlighted in gold'
      : 'Colors: SAFE fragments · accepted cut bonds hidden · gold dashes: selected reconnection guide';
    highlightAtom(null);
  }
  function renderText(e) {
    const text = el('cd-safe-text'); text.replaceChildren();
    for (let i = 0; i < e.fragments.length; i++) {
      if (i) text.append(node('span', ' . ', 'cd-dot'));
      const frag = node('span', undefined, 'cd-safe-fragment');
      frag.style.setProperty('--fragment-color', color(i));
      frag.setAttribute('aria-label', `Fragment F${i + 1}`);
      for (const token of e.tokens.filter(t => t.fragment === i && t.kind !== 'separator')) {
        let span;
        if (token.kind === 'ring') {
          const pair = e.pairs.find(p => p.id === token.pair);
          span = node('button', token.text, `cd-label ${pair.cross_fragment ? 'cd-cross' : 'cd-internal'}`);
          span.type = 'button'; span.dataset.pair = token.pair; span.dataset.lexStart = token.start;
          span.setAttribute('aria-label', `${pair.cross_fragment ? 'Connection' : 'Internal ring'} label ${token.text} at atom ${token.atom}`);
          span.setAttribute('aria-pressed', String(token.pair === selectedPair));
          span.addEventListener('click', () => {selectedPair = token.pair; pause(); render();});
        } else {
          span = node('span', token.text, token.text === '/' || token.text === '\\' ? 'cd-direction' : '');
        }
        if (token.atom !== undefined) {
          span.dataset.lexAtom = token.atom;
          span.title = `Source atom ${token.atom}`;
        }
        frag.append(span);
      }
      text.append(frag);
    }
    const choices = el('cd-pairs'); choices.replaceChildren();
    for (const cross of [true, false]) {
      const group = node('div', undefined, 'cd-pair-group');
      group.append(node('span', cross ? 'Cross-fragment connections' : 'Internal ring closures (not fragment links)', 'label'));
      const buttons = node('div', undefined, 'cd-pair-buttons');
      for (const p of e.pairs.filter(p => p.cross_fragment === cross)) {
        const button = node('button', `${p.label}: ${p.atoms.join(' ↔ ')}`, 'cd-pair-choice');
        button.type = 'button'; button.dataset.pairChoice = p.id;
        button.setAttribute('aria-pressed', String(selectedPair === p.id));
        button.addEventListener('click', () => {selectedPair = p.id; pause(); render();});
        buttons.append(button);
      }
      group.append(buttons); choices.append(group);
    }
    const p = e.pairs.find(pair => pair.id === selectedPair);
    const flow = el('cd-connection-flow'); flow.replaceChildren();
    if (p?.cross_fragment) {
      const parts = [
        ['1 / Accepted cut', `Atom ${p.atoms[0]} ↔ atom ${p.atoms[1]}`, `${p.bond_type.toLowerCase()} bond`],
        ['2 / Temporary endpoints', `[${p.dummy_isotope}*] at each end`, 'Same dummy isotope on both ends; temporary encoding state'],
        ['3 / In the SAFE string', `Label ${p.label} after both atoms`, 'Dummy atoms replaced; atom positions and bond syntax retained']
      ];
      for (const [title, value, description] of parts) {
        const card = node('div'); card.append(node('span', title, 'label'), node('strong', value), node('small', description)); flow.append(card);
      }
    }
    el('cd-pair-detail').textContent = p
      ? `${p.cross_fragment ? 'Connection' : 'Internal ring'} ${p.label}: F${p.fragments[0] + 1} / atom ${p.atoms[0]} ↔ F${p.fragments[1] + 1} / atom ${p.atoms[1]}. Bond type: ${p.bond_type.toLowerCase()}. ${p.cross_fragment ? 'The label follows each attachment atom; the dot does not specify this bond.' : 'Both occurrences are inside one fragment. The label may be reused after a pair closes.'}`
      : '';
  }
  function renderMapping(e) {
    const body = el('cd-mapping-body'); body.replaceChildren();
    e.fragments.forEach((f, i) => {
      const row = node('tr');
      const first = node('td');
      const button = node('button', `F${i + 1}`, 'cd-fragment-choice');
      button.type = 'button'; button.style.borderColor = color(i);
      button.dataset.cdFragment = i;
      button.setAttribute('aria-pressed', String(selectedFragment === i));
      button.addEventListener('click', () => {selectedFragment = i; selectedPair = null; pause(); render();});
      first.append(button); row.append(first);
      row.append(node('td', f.vocab_key));
      row.append(node('td', f.node_id === null ? 'Not in vocabulary' : String(f.node_id), f.node_id === null ? 'cd-missing' : ''));
      body.append(row);
    });
  }
  function render() {
    const focused = document.activeElement;
    const restore = focused?.dataset.pairChoice !== undefined ? `[data-pair-choice="${focused.dataset.pairChoice}"]`
      : focused?.dataset.cdFragment !== undefined ? `[data-cd-fragment="${focused.dataset.cdFragment}"]`
      : focused?.dataset.lexStart !== undefined ? `[data-lex-start="${focused.dataset.lexStart}"]` : null;
    const e = sample();
    el('cd-badge').textContent = `${e.bpe_groups.length} GraphBPE motifs → ${e.fragments.length} SAFE fragments · ${e.exact ? 'boundaries preserved' : 'boundaries changed'}`;
    el('cd-badge').classList.toggle('cd-changed', !e.exact);
    el('cd-source').textContent = `${e.chembl_id} · original input record ${e.record_index.toLocaleString()} · replay and isomeric round trip verified`;
    el('cd-input').textContent = e.smiles;
    el('cd-step-title').textContent = `${step + 1}. ${labels[step]}`;
    el('cd-step-copy').textContent = descriptions(e)[step];
    el('cd-status').textContent = `Step ${step + 1} of 6: ${labels[step]}. ${e.chembl_id}.`;
    el('cd-prev').disabled = step === 0;
    el('cd-next').disabled = step === 5;
    root.querySelectorAll('[data-demo-step]').forEach((button, i) => {
      button.setAttribute('aria-pressed', String(i === step));
      button.classList.toggle('cd-complete', i < step);
    });
    el('cd-safe-panel').hidden = step < 3;
    el('cd-partition-panel').hidden = step >= 3;
    el('cd-mapping').hidden = step !== 4;
    el('cd-decoded').hidden = step !== 5;
    el('cd-decoded-smiles').textContent = e.decoded;
    const groups = el('cd-group-list'); groups.replaceChildren();
    const sourceGroups = step < 2 ? e.bpe_groups : e.fragments.map(f => f.atoms);
    sourceGroups.forEach((g, i) => {
      const item = node('div', undefined, 'cd-group-item');
      item.style.borderLeftColor = color(i);
      item.append(node('strong', `${step < 2 ? 'M' : 'F'}${i + 1}`));
      item.append(node('span', `Atoms ${g.join(', ')}`));
      groups.append(item);
    });
    el('cd-group-list').hidden = step === 0;
    el('cd-partition-intro').textContent = step === 0
      ? 'Follow the same numbered atoms through partitioning, SAFE labels and reconstruction. All molecular drawings come from the saved experimental record.'
      : step === 1 ? 'GraphBPE groups, in recorded order. Each group has a node-vocabulary ID. SAFE serialization may reorder them.'
      : 'Final fragments, in SAFE serialization order. Membership is checked as atom sets, not by matching fragment order.';
    el('cd-stereo-note').hidden = e.exact || step < 2;
    el('cd-stereo-note').textContent = 'Retained: C11=C12 (STEREOE). The /C=C/ substring remains inside F1. The slashes on neighboring single bonds encode the double-bond geometry. This is the current repository’s stereo-protection policy.';
    renderText(e); renderMapping(e); renderGraph(e);
    if (restore) root.querySelector(restore)?.focus({preventScroll: true});
  }
  async function init() {
    try {
      const response = await fetch('connection-demo.json?v=20261103');
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      data = await response.json();
      selectedPair = sample().pairs.find(p => p.cross_fragment).id;
      labels.forEach((label, i) => {
        const button = node('button', `${i + 1}  ${label}`);
        button.type = 'button'; button.dataset.demoStep = i;
        button.addEventListener('click', () => {pause(); setStep(i);});
        el('cd-steps').append(button);
      });
      el('cd-example').addEventListener('change', event => {
        pause(); exampleIndex = Number(event.target.value); step = 0; selectedFragment = 0;
        selectedPair = sample().pairs.find(p => p.cross_fragment).id; render();
      });
      el('cd-prev').addEventListener('click', () => {pause(); setStep(step - 1);});
      el('cd-next').addEventListener('click', () => {pause(); setStep(step + 1);});
      el('cd-play').addEventListener('click', () => {
        if (timer) {pause(); return;}
        if (step === 5) setStep(0);
        el('cd-play').textContent = 'Pause'; el('cd-play').setAttribute('aria-pressed', 'true');
        timer = setInterval(() => setStep(step + 1), 5000);
      });
      document.addEventListener('visibilitychange', () => {if (document.hidden) pause();});
      render(); el('cd-loading').hidden = true; el('cd-content').hidden = false;
    } catch (error) {
      el('cd-loading').textContent = `The walkthrough could not load (${error.message}). Please refresh the page.`;
      el('cd-loading').setAttribute('role', 'alert');
    }
  }
  init();
})();
